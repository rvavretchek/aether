      '  memoryCost: 19456,',
      '  timeCost: 2,',
      '  parallelism: 1,',
      '} as const;',
      '',
      '// Hash "isca" com o MESMO custo de ARGON2_OPTIONS, calculado uma única vez e',
      '// cacheado — usado só pra pagar o custo de um argon2.verify() real quando o',
