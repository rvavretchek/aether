      '  dummyHashPromise ??= argon2.hash(',
      "    'dummy-password-constant-time-verify',",
      '    {',
      '      ...ARGON2_OPTIONS,',
      "      secret: Buffer.from('dummy-pepper-constant-time-verify'),",
      '    },',
      '  );',
      '  return dummyHashPromise;',
      '}',
      '',
      'export class Argon2AuthProvider implements AuthProvider {',
      '  constructor(',
      '    private readonly secrets: SecretsProvider,',
      '    private readonly db: UserLookup,',
      '  ) {}',
      '',
      '  async hash(password: string): Promise<string> {',
      "    const pepper = this.secrets.getSecret('ARGON2_PEPPER');",
      '    return argon2.hash(password, {',
      '      ...ARGON2_OPTIONS,',
      '      secret: Buffer.from(pepper),',
      '    });',
      '  }',
      '',
      '  async authenticate(',
      '    email: string,',
      '    password: string,',
      '    tenantId: string,',
      '  ): Promise<AuthenticatedUser | null> {',
      '    const user = await this.db.user.findUnique({',
      '      where: { tenantId_email: { tenantId, email } },',
      '    });',
      '    if (!user) {',
      '      const dummy = await getDummyHash();',
      '      await argon2',
      '        .verify(dummy, password, {',
      "          secret: Buffer.from('dummy-pepper-constant-time-verify'),",
      '        })',
      '        .catch(() => false);',
      '      return null;',
      '    }',
      '',
      "    const pepper = this.secrets.getSecret('ARGON2_PEPPER');",
      '    const ok = await argon2',
      '      .verify(user.passwordHash, password, { secret: Buffer.from(pepper) })',
      '      // Hash corrompido/malformado no banco lança em vez de retornar false —',
      '      // não pode virar um 500 não tratado quebrando a garantia de resposta',
      '      // uniforme da AC #9.',
      '      .catch(() => false);',
      '    if (!ok) {',
      '      return null;',
      '    }',
      '',
      '    return {',
      '      id: user.id,',
      '      tenantId: user.tenantId,',
      '      email: user.email,',
      '      isAdmin: user.isAdmin,',
      '    };',
      '  }',
      '',
      '  async verifyToken(token: string): Promise<VerifiedToken | null> {',
      '    try {',
      '      const key = new TextEncoder().encode(',
      "        this.secrets.getSecret('JWT_SIGNING_KEY'),",
      '      );',
      '      const { payload } = await jwtVerify(token, key, {',
      '        // Nunca confiar no `alg` do próprio token — fixado explicitamente',
      '        // (Zero Trust, NFR2/§8.1, Story 2.1 AC #10).',
      "        algorithms: ['HS256'],",
      '      });',
      '      if (',
      "        typeof payload.sub !== 'string' ||",
      "        typeof payload.tenantId !== 'string' ||",
      "        typeof payload.isAdmin !== 'boolean'",
      '      ) {',
      '        return null;',
      '      }',
      '      return {',
      '        userId: payload.sub,',
      '        tenantId: payload.tenantId,',
      '        isAdmin: payload.isAdmin,',
      '      };',
      '    } catch {',
      '      // Assinatura inválida, token expirado, alg divergente, malformado — tudo',
      '      // cai aqui. Nunca lança, mesmo formato uniforme dos outros métodos.',
      '      return null;',
      '    }',
      '  }',
      '',
      '  async findUserByEmail(',
      '    tenantId: string,',
      '    email: string,',
      '  ): Promise<AuthenticatedUser | null> {',
      '    const user = await this.db.user.findUnique({',
      '      where: { tenantId_email: { tenantId, email } },',
      '    });',
      '    return user',
      '      ? {',
      '          id: user.id,',
      '          tenantId: user.tenantId,',
      '          email: user.email,',
      '          isAdmin: user.isAdmin,',
      '        }',
      '      : null;',
      '  }',
      '',
      '  async findUserById(userId: string): Promise<AuthenticatedUser | null> {',
      '    const user = await this.db.user.findUnique({ where: { id: userId } });',
      '    return user',
      '      ? {',
      '          id: user.id,',
      '          tenantId: user.tenantId,',
      '          email: user.email,',
      '          isAdmin: user.isAdmin,',
      '        }',
      '      : null;',
      '  }',
      '',
      '  async setPassword(userId: string, newPassword: string): Promise<void> {',
      '    const passwordHash = await this.hash(newPassword);',
      '    await this.db.user.update({ where: { id: userId }, data: { passwordHash } });',
      '  }',
      '}',
